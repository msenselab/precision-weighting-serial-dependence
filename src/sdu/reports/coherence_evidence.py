"""Figures for v3 model recovery, matched behavioral effects and likelihood diagnostics."""
import numpy as np
import matplotlib.pyplot as plt
from matplotlib.ticker import FuncFormatter, MaxNLocator

INK = "#263940"
COLORS = {2: "#287CA6", 1: "#617D71"}


def switch_confusion(matrix):
    fig, ax = plt.subplots(figsize=(4.8, 4.1), layout="constrained")
    proportions = matrix.to_numpy() / matrix.sum(axis=1).to_numpy()[:, None]
    ax.imshow(proportions, cmap="Blues", vmin=0, vmax=1)
    ax.set_xticks([0, 1], ["S0", "S3"])
    ax.set_yticks([0, 1], ["S0", "S3"])
    ax.set(xlabel="Selected model", ylabel="Generating model")
    for row in range(2):
        for col in range(2):
            value = proportions[row, col]
            ax.text(col, row, f"{value:.0%}", ha="center", va="center", fontsize=19,
                    color="white" if value > .5 else INK)
    return fig


def switch_recovery(matrix, cohorts):
    fig, axes = plt.subplots(1, 2, figsize=(9.5, 3.8), layout="constrained")
    axes[0].imshow(matrix.to_numpy()/100, cmap="Blues", vmin=0, vmax=1)
    axes[0].set_xticks([0, 1], ["S0", "S3"])
    axes[0].set_yticks([0, 1], ["S0", "S3"])
    axes[0].set(xlabel="Selected model", ylabel="Generating model", title="S0/S3 recovery — 100 cohorts each")
    for row in range(2):
        for col in range(2):
            value = matrix.iloc[row, col]
            axes[0].text(col, row, f"{value:.0f}%", ha="center", va="center", fontsize=16,
                         color="white" if value > 50 else INK)
    for name, color in (("S0", COLORS[2]), ("S3", COLORS[1])):
        d = cohorts[cohorts.generator == name].delta_AIC_S3_minus_S0
        axes[1].hist(d, bins=15, alpha=.65, color=color, label=f"Generated by {name}", edgecolor="white")
    axes[1].axvline(0, color=INK, lw=1)
    axes[1].set(xlabel="Mean AIC: S3 minus S0", ylabel="Cohorts", title="Model-selection evidence")
    axes[1].xaxis.set_major_formatter(FuncFormatter(lambda x, _: f"{x:.1f}"))
    handles, labels = axes[1].get_legend_handles_labels()
    fig.legend(handles, labels, loc="outside lower center", frameon=False, ncol=2)
    return fig


def experiment_contrasts(frame):
    d = frame[frame.contrast.str.endswith("Low - High") | (frame.exp == 0)].copy()
    d = d.set_index("exp").loc[[2, 1, 0]]
    labels = ["Experiment 1: Low − High", "Experiment 2: Low − High", "Experiment 1 − Experiment 2"]
    fig, ax = plt.subplots(figsize=(8.5, 3.4), layout="constrained")
    for y, (_, row), color in zip([2, 1, 0], d.iterrows(), [COLORS[2], COLORS[1], INK]):
        ax.errorbar(row.estimate, y, xerr=[[row.estimate-row.ci_low], [row.ci_high-row.estimate]],
                    fmt="o", color=color, capsize=4, ms=6, lw=1.5)
    ax.axvline(0, color="#ABB4B8", lw=1)
    ax.set_yticks([2, 1, 0], labels)
    ax.set(ylim=(-.5, 2.5), xlabel="Controlled lag-1 slope difference (95% CI)")
    ax.xaxis.set_major_formatter(FuncFormatter(lambda x, _: f"{x:.2f}"))
    ax.grid(axis="x", color="#E8ECED", lw=.6)
    return fig


def phi_profiles(curves):
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8), sharex=True, sharey=True, layout="constrained")
    for ax, exp in zip(axes, (2, 1)):
        d = curves[curves.exp == exp]
        for _, g in d.groupby("Sub"):
            g = g.sort_values("phi_high")
            ax.plot(g.phi_high, g.loss, color=COLORS[exp], alpha=.2, lw=.9)
        regular = d[np.isclose(d.phi_high*10, np.round(d.phi_high*10))].copy()
        regular["grid"] = regular.phi_high.round(1)
        med = regular.drop_duplicates(["Sub", "grid"]).groupby("grid").loss.median()
        ax.plot(med.index, med.values, color=COLORS[exp], lw=2.5, label="Median profile")
        ax.axhline(3.8414588207, color=INK, ls="--", lw=1, label="Loss reference: 3.84")
        ax.set(xlim=(0, 1), ylim=(0, 20), xlabel=r"Fixed $\phi^H$",
               title=f"Experiment {1 if exp == 2 else 2}")
        ax.grid(axis="y", color="#E8ECED", lw=.6)
    axes[0].set_ylabel("Twice the log-likelihood loss")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="outside lower center", frameon=False, ncol=2)
    return fig


def offset_recovery(table):
    fig, axes = plt.subplots(2, 2, figsize=(7.5, 6.2), layout="constrained")
    fig.get_layout_engine().set(h_pad=.10, hspace=.08)
    for row, exp in enumerate((2, 1)):
        for col, parameter in enumerate(("offset_high", "offset_low")):
            ax = axes[row, col]
            d = table[(table.exp == exp) & (table.parameter == parameter)]
            mean = d.groupby("Sub")[["true", "fitted"]].mean()
            lo, hi = min(d.true.min(), d.fitted.min()), max(d.true.max(), d.fitted.max())
            pad = max((hi-lo)*.05, .005)
            ax.plot([lo-pad, hi+pad], [lo-pad, hi+pad], color="#A7B0B4", ls="--", lw=1)
            ax.scatter(d.true, d.fitted, color=COLORS[exp], s=10, alpha=.12, edgecolor="none")
            ax.scatter(mean.true, mean.fitted, color=COLORS[exp], s=24, edgecolor="white", lw=.4)
            ax.set(xlim=(lo-pad, hi+pad), ylim=(lo-pad, hi+pad),
                   title=f"Experiment {1 if exp == 2 else 2} — {'High' if col == 0 else 'Low'} offset")
            ax.xaxis.set_major_formatter(FuncFormatter(lambda x, _: f"{x:.2f}"))
            ax.yaxis.set_major_formatter(FuncFormatter(lambda x, _: f"{x:.2f}"))
            ax.xaxis.set_major_locator(MaxNLocator(4)); ax.yaxis.set_major_locator(MaxNLocator(4))
            ax.set_aspect("equal", adjustable="box")
    fig.supxlabel("True offset (s)"); fig.supylabel("Recovered offset (s)")
    return fig


def sensitivity_power(power):
    fig, axes = plt.subplots(1, 2, figsize=(9.5, 3.8), sharey=True, layout="constrained")
    for ax, scenario, title in zip(axes, ("null", "matched"), ("Zero effect: false positives", "Exp 1-sized effect: detection")):
        d = power[power.scenario == scenario].set_index("method").loc[["Trial LMM", "Participant test"]]
        key = "significant" if scenario == "null" else "positive"
        values = d[f"{key}_rate"].to_numpy()
        low, high = d[f"{key}_ci_low"].to_numpy(), d[f"{key}_ci_high"].to_numpy()
        ax.bar([0, 1], values, width=.58, color=[COLORS[2], COLORS[1]],
               yerr=np.array([values-low, high-values]), capsize=4)
        ax.set_xticks([0, 1], ["Trial LMM", "Participant test"])
        ax.set(title=title, ylim=(0, 1.08))
        ax.grid(axis="y", color="#E8ECED", lw=.6)
        ax.yaxis.set_major_formatter(FuncFormatter(lambda x, _: f"{x:.0%}"))
        if scenario == "null":
            ax.axhline(.05, color=INK, lw=1, ls="--")
    axes[0].set_ylabel("Proportion of 100 simulated cohorts")
    return fig


def sensitivity_recovery(cohorts):
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.6), sharex=True, sharey=True, layout="constrained")
    for ax, scenario, color in zip(axes, ("null", "matched"), (COLORS[1], COLORS[2])):
        d = cohorts[cohorts.scenario == scenario]
        ax.hist(d.recovered_effect, bins=12, color=color, alpha=.7, edgecolor="white")
        ax.axvline(d.true_effect.mean(), color=INK, lw=1.5, ls="--", label="Generating effect")
        ax.set(title="Zero effect" if scenario == "null" else "Exp 1-sized effect",
               xlabel="Recovered cohort-mean lag-slope difference")
        ax.xaxis.set_major_formatter(FuncFormatter(lambda x, _: f"{x:.2f}"))
    axes[0].set_ylabel("Cohorts")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="outside lower center", frameon=False)
    return fig
